import { chromium } from "/home/vansin/agent-network-dashboard/node_modules/playwright/index.mjs";
const UI = "http://127.0.0.1:8930/";
const HUB = "http://127.0.0.1:8899";
const U = process.env.ISO_USER, P = process.env.ISO_PASS;
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const page = await browser.newPage();
const errs = [], calls = [];
page.on("console", m => { if (m.type() === "error") errs.push(m.text().slice(0, 240)); });
page.on("response", r => { if (r.url().includes("/api/")) calls.push(`${r.status()} ${r.request().method()} ${r.url().replace("http://127.0.0.1:8899", "").slice(0, 100)}`); });
await page.goto(UI, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(2500);
const inputs = page.locator("input");
await inputs.nth(0).fill(HUB);
await inputs.nth(1).fill(U);
await inputs.nth(2).fill(P);
await page.getByText("登录工作区").first().click();
await page.waitForTimeout(6000);
console.log("AFTER_LOGIN_BODY:", JSON.stringify((await page.locator("body").innerText()).slice(0, 900)));
console.log("CALLS:", JSON.stringify(calls.slice(0, 14)));
console.log("ERRS:", JSON.stringify(errs.slice(0, 6)));
await page.screenshot({ path: "/tmp/opencode/ui-after-login.png", fullPage: false });
await browser.close();
