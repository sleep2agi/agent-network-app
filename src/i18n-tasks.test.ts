import { setLanguagePreference, t as tr } from './i18n';
import { taskCopy, taskText } from './i18n-tasks';
import { ownerLabel, personDisplay, dueInfo, formatDueFull, validationText } from './i18n-task-presentation';
let p=0,t=0;
const ck=(name:string,ok:boolean)=>{t++;if(ok)p++;console.log(`${ok?'PASS':'FAIL'}: ${name}`);};
const fields=(s:string)=>JSON.stringify([...s.matchAll(/\{(\w+)\}/g)].map(m=>m[1]).sort());
ck('all bilingual placeholders match',taskCopy.every(([zh,en])=>fields(zh)===fields(en)));
setLanguagePreference('en');
ck('column and priority labels translate',taskText('需求池')==='Backlog'&&taskText('高')==='High');
ck('unassigned is presentation, not stored identity',ownerLabel({owner:null,assignee:''},[])==='Unassigned');
ck('legacy user text identical to a label remains verbatim',ownerLabel({assignee:'未分配'},[])==='未分配');
const ref={kind:'user' as const,id:'u1'};
ck('real member names remain verbatim',personDisplay(ref,[{...ref,name:'未分配',networkId:'n'}]).name==='未分配');
ck('unknown member hint translates without inventing identity',personDisplay(ref,[]).name==='Unknown member (u1)');
ck('due date full label translates',formatDueFull('2026-10-01')==='2026-10-01 All day');
ck('due calculation and tone unchanged',dueInfo('2026-09-29','2026-09-30').tone==='overdue'&&dueInfo('2026-09-29','2026-09-30').label==='1d overdue');
ck('subtask progress interpolates',tr('tasks.progress',{done:1,total:3})==='1/3 complete');
ck('project validation translates',validationText('先写项目名')==='Enter a project name first');
setLanguagePreference('zh');
ck('switch restores Chinese immediately',taskText('需求池')==='需求池'&&tr('tasks.progress',{done:1,total:3})==='1/3 完成');
console.log(`${p}/${t} passed`);process.exit(p===t?0:1);
