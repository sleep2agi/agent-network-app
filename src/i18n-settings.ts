const keys = new Map<string, string>(copy.map(([zh], index) => [zh, `settings.copy.${index}`]));
/** Translate known presentation model labels only, never profile names or other user data. */
export const settingsText = (value: string) => { const key = keys.get(value); return key ? t(key) : value; };
export const settingsCopyEntries = copy;

/** Both columns of a known Chinese source string. Missing values are not translated. */
export function settingsPair(value: string): readonly [string, string] | undefined {
  const key = keys.get(value);
  return key ? settingsTranslations[key] : undefined;
}

