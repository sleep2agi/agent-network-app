import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { acceptProfileCredential, clearProfileUnauthorized, isCurrentProfileCredential, onProfileUnauthorized, reportProfileAuthResponse, serializeCredentialWrite } from './profile-auth-state';
import { createSessionStore } from './session-registry';
const data = new Map<string, string>();
const store = createSessionStore({ get: async k => data.get(k) ?? null, set: async (k,v) => { data.set(k,v); }, del: async k => { data.delete(k); } }, { newId: () => 'race-profile' });
let passed = 0;
const old = await store.save({ serverUrl: 'https://hub.example.test', username: 'fixture', token: 'TEST-ONLY-old' });
const id = old.profileId!;
let redirects = 0;
const stop = onProfileUnauthorized(id => { if (id === old.profileId) redirects++; });
reportProfileAuthResponse(401, old.profileId, undefined, old.token);
await store.markReauth(old.profileId!, true);
const saved = await serializeCredentialWrite(async () => {
  const next = await store.save({ ...old, token: 'TEST-ONLY-new' });
  acceptProfileCredential(id, next.token);
  return next;
});
reportProfileAuthResponse(401, old.profileId, undefined, old.token);
assert.equal(redirects, 1, 'late old-token401 must not redirect the freshly signed-in account'); passed++;
assert.equal((await store.loadIndex()).sessions[0].requiresReauth, undefined); passed++;
assert.equal(isCurrentProfileCredential(id, old.token), false, 'pending old callbacks must not navigate'); passed++;
reportProfileAuthResponse(401, id, undefined, saved.token);
assert.equal(redirects, 2, 'genuine new-token401 still requires reauthentication'); passed++;
clearProfileUnauthorized(id);
let unblock!: () => void;
const paused = new Promise<void>(r => { unblock = r; });
const pendingMark = serializeCredentialWrite(async () => { await paused; await store.markReauth(id, true); });
const pendingSave = serializeCredentialWrite(async () => {
  const next = await store.save({ ...saved, token: 'TEST-ONLY-next' });
  acceptProfileCredential(id, next.token);
});
unblock();
await Promise.all([pendingMark, pendingSave]);
assert.equal((await store.loadIndex()).sessions[0].requiresReauth, undefined, 'old mark finishes before clean saved index'); passed++;
await assert.rejects(serializeCredentialWrite(async () => { throw new Error('synthetic save failure'); }));
assert.equal(isCurrentProfileCredential(id, 'TEST-ONLY-next'), true, 'failed persistence must not accept another token'); passed++;
let queueContinued = false;
await serializeCredentialWrite(async () => { queueContinued = true; });
assert.equal(queueContinued, true, 'a failed save must not poison subsequent writes'); passed++;
let otherEvents = 0;
const stopOther = onProfileUnauthorized(p => { if (p === 'another-profile') otherEvents++; });
reportProfileAuthResponse(401, 'another-profile', undefined, 'TEST-ONLY-other');
assert.equal(otherEvents, 1); passed++;
stopOther(); stop();
const storage = readFileSync(new URL('./storage.ts', import.meta.url), 'utf8');
const app = readFileSync(new URL('../App.tsx', import.meta.url), 'utf8');
assert(storage.includes('acceptProfileCredential(sessionIdOf(saved), saved.token)') && storage.includes('current.token !== requestToken')); passed++;
assert(app.includes('markHubProfileRequiresReauth(profileId, true, cfg.token)') && app.includes('superseded || !isCurrentProfileCredential(profileId, cfg.token)')); passed++;
assert.equal(passed, 10);
console.log('PASS reauth race10/10: late401, pending callback/write, current401 and other profile; synthetic credentials only');
