import { defaultFields, FIELD_IDS, FIELDS_KEY, loadFields, moveField, parseFields, saveFields, toggleField } from './task-list-fields';
import { readFileSync } from 'node:fs';
let p = 0, t = 0;
const ck = (name: string, ok: boolean) => { t++; if (ok) p++; console.log(`${ok ? 'PASS' : 'FAIL'}: ${name}`); };
ck('complete catalog', defaultFields().length === FIELD_IDS.length);
ck('secondary columns hidden', defaultFields().filter(f => !f.visible).map(f => f.id).join() === 'participants,issues');
for (const raw of [null, '{', '{}', 'false', '[null,4,"x"]']) ck(`invalid preference ${raw}`, parseFields(raw).length === FIELD_IDS.length);
const repaired = parseFields('[{"id":"title","visible":false},{"id":"owner","visible":false},{"id":"owner"},{"id":"bogus"}]');
ck('title always visible', repaired[0].visible);
ck('deduplicates and rejects unknown fields', repaired.length === FIELD_IDS.length);
ck('preserves hidden column', !repaired.find(f => f.id === 'owner')!.visible);
ck('title toggle locked', toggleField(defaultFields(), 'title')[0].visible);
ck('toggle participant', toggleField(defaultFields(), 'participants').find(f => f.id === 'participants')!.visible);
const moved = moveField(defaultFields(), 'status', 'owner');
ck('move order', moved[1].id === 'status' && moved[2].id === 'owner');
ck('move does not mutate defaults', defaultFields()[1].id === 'owner');
ck('round trip', JSON.stringify(parseFields(JSON.stringify(moved))) === JSON.stringify(moved));
ck('future field appended with default', parseFields('[{"id":"title","visible":true}]').find(f => f.id === 'issues')?.visible === false);
let stored = '';
Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: { getItem: () => null, setItem: (key: string, raw: string) => { if (key === FIELDS_KEY) stored = raw; } } });
saveFields(moved);
ck('device preference stored', stored === JSON.stringify(moved));
ck('session snapshot', JSON.stringify(loadFields()) === stored);
Object.defineProperty(globalThis, 'localStorage', { configurable: true, get: () => { throw new Error('denied'); } });
saveFields(defaultFields());
ck('denied storage preserves usable preference', loadFields()[1].id === 'owner');
const board = readFileSync(new URL('./RequirementBoard.tsx', import.meta.url), 'utf8').replace(/\r\n?/g, '\n');
const list = board.slice(board.indexOf('const list = () =>'), board.indexOf('const body ='));
ck('list layout branches on width only, not pointer', /if \(narrow\)/.test(list) && !/if \([^)]*!pointer/.test(list));
const ui = readFileSync(new URL('./TaskListFields.tsx', import.meta.url), 'utf8').replace(/\r\n?/g, '\n');
ck('touch gets named up/down controls and no keyboard autofocus', ui.includes("'fields.up' : 'fields.down'") && ui.includes('autoFocus={!touch}'));
console.log(`${p}/${t} passed`); if (p !== t) process.exit(1);
